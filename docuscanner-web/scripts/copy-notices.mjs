// Writes public/licenses/third-party-notices.txt: the copyright and licence notices that the open-source components of the website require
// to accompany them. The footer links to it. It is rebuilt from package-lock.json and the installed packages before `dev` and `build` (see
// package.json), the same way the font, PDF and OCR assets are copied, so it cannot fall behind the lock file.
//
//   Part 1  files the site serves that are not npm bundles: the PDF.js runtime and its fonts and decoders, the OCR engine and model, the QPDF
//           engine, and the fonts (their licences are copied from the packages and from scripts/notices/)
//   Part 2  every npm package that is not development-only, grouped by licence text, each with its own copyright line
//
// This file must never stop a build: any problem is printed as a warning and the script exits 0.

import { existsSync, mkdirSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { createHash } from "node:crypto";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const out = join(root, "public", "licenses", "third-party-notices.txt");
const rule = "=".repeat(78);
const thin = "-".repeat(78);

const read = (file) => {
  try {
    return readFileSync(file, "utf8").replace(/\r\n/g, "\n").trim();
  } catch {
    return null;
  }
};
const json = (file) => {
  try {
    return JSON.parse(readFileSync(file, "utf8"));
  } catch {
    return null;
  }
};

try {
  const lock = json(join(root, "package-lock.json"));
  if (!lock) throw new Error("package-lock.json could not be read");
  const lines = [];
  const add = (...l) => lines.push(...l);

  add(
    "THIRD-PARTY NOTICES: FreePDFScanner website",
    "",
    "The website is built from open-source components. The notices below are the ones their licences ask to be shown with them.",
    "Generated by scripts/copy-notices.mjs from package-lock.json and the installed packages. Part 1 covers files the site serves as they are;",
    "Part 2 covers the npm packages the application is built from (development-only tools are not included, they are not part of what visitors receive).",
    "",
  );

  // ---- Part 1 ----------------------------------------------------------------------------------------------------------------
  add(rule, "PART 1: FILES SERVED WITH THE SITE", rule, "");
  const section = (title, intro, files) => {
    add(thin, title, thin);
    if (intro) add(intro, "");
    for (const [label, file] of files) {
      const text = read(file);
      add(text ? `[${label}]` : `[${label}: file not present in this build]`, text ?? "", "");
    }
  };
  section("PDF.js (Mozilla): /pdfjs", "Worker, character maps, standard fonts and image decoders used to read PDFs in the browser. Licensed under the Apache License 2.0.", [
    ["PDF.js licence", join(root, "public", "pdfjs", "LICENSE")],
    ["Foxit-named standard fonts (PDFium licence, BSD 3-clause)", join(root, "public", "pdfjs", "standard_fonts", "LICENSE_FOXIT")],
    ["Liberation Sans (SIL Open Font License 1.1)", join(root, "public", "pdfjs", "standard_fonts", "LICENSE_LIBERATION")],
    ["JBIG2 decoder (PDFium licence)", join(root, "public", "pdfjs", "wasm", "LICENSE_JBIG2")],
    ["JBIG2 decoder (PDF.js)", join(root, "public", "pdfjs", "wasm", "LICENSE_PDFJS_JBIG2")],
    ["OpenJPEG JPEG 2000 decoder (BSD 2-clause)", join(root, "public", "pdfjs", "wasm", "LICENSE_OPENJPEG")],
    ["OpenJPEG (PDF.js)", join(root, "public", "pdfjs", "wasm", "LICENSE_PDFJS_OPENJPEG")],
    ["qcms colour management (MIT)", join(root, "public", "pdfjs", "wasm", "LICENSE_QCMS")],
    ["qcms (PDF.js)", join(root, "public", "pdfjs", "wasm", "LICENSE_PDFJS_QCMS")],
  ]);
  section(
    "Tesseract OCR: /ocr",
    "Tesseract.js, its WebAssembly core (Tesseract and Leptonica) and the English model (tessdata_best, \"All data in the repository are licensed under the Apache-2.0 License\"). All Apache License 2.0; the licence text is the one printed under PDF.js above and in the files below.",
    [
      ["tesseract.js", join(root, "node_modules", "tesseract.js", "LICENSE.md")],
      ["tesseract.js-core", join(root, "node_modules", "tesseract.js-core", "LICENSE")],
    ],
  );
  section("QPDF engine: /qpdf", null, [["QPDF, libjpeg-turbo and zlib", join(root, "scripts", "notices", "qpdf-wasm.txt")]]);
  const fontDir = join(root, "public", "fonts", "docx", "licenses");
  const fontFiles = existsSync(fontDir) ? readdirSync(fontDir).filter((f) => f.endsWith(".txt")).sort() : [];
  section(
    "Fonts",
    "Carlito, Arimo, Tinos, Caladea and Cousine (served from /fonts/docx) are SIL Open Font License 1.1 fonts, metric-compatible with Calibri, Arial, Times New Roman, Cambria and Courier New. Geist and Geist Mono (the site's own typeface, served through Next.js) are SIL Open Font License 1.1 too.",
    [...fontFiles.map((f) => [f.replace(/-LICENSE\.txt$/, ""), join(fontDir, f)]), ["Geist", join(root, "scripts", "notices", "geist-OFL.txt")]],
  );

  // ---- Part 2 ----------------------------------------------------------------------------------------------------------------
  add(rule, "PART 2: NPM PACKAGES USED BY THE APPLICATION", rule, "");
  const groups = new Map();
  const noFile = [];
  let count = 0;
  for (const [key, entry] of Object.entries(lock.packages)) {
    if (!key || entry.dev) continue;
    const dir = join(root, key);
    const pkg = json(join(dir, "package.json"));
    if (!pkg) continue; // an optional package for another platform that is not installed here
    count++;
    const name = key.replace(/^.*node_modules\//, "");
    const licence = typeof pkg.license === "string" ? pkg.license : (pkg.license?.type ?? entry.license ?? "unknown");
    const file = existsSync(dir) ? readdirSync(dir).find((f) => /^(licen[cs]e|copying)/i.test(f)) : undefined;
    const text = file ? read(join(dir, file)) : null;
    const author = typeof pkg.author === "string" ? pkg.author : pkg.author?.name;
    if (!text) {
      noFile.push({ name, version: pkg.version, licence, author: author ?? (typeof pkg.repository === "string" ? pkg.repository : pkg.repository?.url) ?? "" });
      continue;
    }
    const copyright = text.split("\n").filter((l) => /^\s*(copyright|\(c\)|©)/i.test(l)).map((l) => l.trim()).slice(0, 3);
    const body = text.split("\n").filter((l) => !/^\s*(copyright|\(c\)|©)/i.test(l)).join("\n").replace(/\s+/g, " ").trim();
    const id = createHash("sha1").update(body).digest("hex");
    if (!groups.has(id)) groups.set(id, { licence, text, packages: [] });
    groups.get(id).packages.push({ name, version: pkg.version, copyright });
  }
  for (const g of [...groups.values()].sort((a, b) => b.packages.length - a.packages.length)) {
    add(thin, `${g.licence}: ${g.packages.length} package${g.packages.length === 1 ? "" : "s"}`, thin, g.text, "", "Packages under this licence text (and their own copyright lines):");
    for (const p of g.packages.sort((a, b) => a.name.localeCompare(b.name))) add(`  ${p.name}@${p.version}${p.copyright.length ? "  " + p.copyright.join(" / ") : ""}`);
    add("");
  }
  if (noFile.length) {
    add(thin, `Packages that declare their licence in package.json but ship no licence file: ${noFile.length}`, thin);
    add("Each is used under the licence it declares (for MIT, ISC, BSD and similar licences the licence text is the standard one for that name, with the holder named below).", "");
    for (const p of noFile.sort((a, b) => a.name.localeCompare(b.name))) add(`  ${p.name}@${p.version}  ${p.licence}${p.author ? "  by " + p.author : ""}`);
    add("");
  }

  mkdirSync(dirname(out), { recursive: true });
  writeFileSync(out, lines.join("\n") + "\n");
  console.log(`[copy-notices] Wrote public/licenses/third-party-notices.txt (${count} npm packages, ${groups.size} licence texts)`);
} catch (e) {
  console.warn("[copy-notices] Could not write the notices file:", e?.message ?? e);
}
