// Builds data/geo/ng-admin-units.json and the idempotent SQL seed from the OCHA
// COD-AB Nigeria workbook (nga_admin_boundaries.xlsx, sheets nga_admin1 + nga_admin2).
//   node scripts/build-ng-admin-units.mjs <path-to-nga_admin_boundaries.xlsx>
// Names and parents are copied from the source, never typed or guessed here; the
// only addition is the ISO 3166-2 code of each state, matched by name against the
// iso-3166-2 package and failing loudly if any state does not match.

import { readFileSync, writeFileSync } from "node:fs";
import ExcelJS from "exceljs";
import iso3166 from "iso-3166-2";

const src = process.argv[2];
if (!src) throw new Error("usage: node scripts/build-ng-admin-units.mjs <nga_admin_boundaries.xlsx>");

const wb = new ExcelJS.Workbook();
await wb.xlsx.readFile(src);

function rows(sheet) {
  const ws = wb.getWorksheet(sheet);
  const head = ws.getRow(1).values;
  const out = [];
  ws.eachRow((row, n) => {
    if (n === 1) return;
    const o = {};
    row.values.forEach((v, i) => { if (head[i]) o[head[i]] = v; });
    out.push(o);
  });
  return out;
}

const norm = (s) => s.toLowerCase().replace(/[^a-z]/g, "");
const isoSubs = iso3166.country("NG").sub;
const isoByName = new Map(Object.entries(isoSubs).map(([code, s]) => [norm(s.name), code]));
// ISO names the FCT "Abuja Federal Capital Territory".
isoByName.set(norm("Federal Capital Territory"), "NG-FC");

const FCT_PCODE_NAME = "federal capital territory";
const states = rows("nga_admin1")
  .map((r) => {
    const fct = r.adm1_name.toLowerCase().includes("federal capital") || norm(r.adm1_name) === "fct";
    const iso = fct ? "NG-FC" : isoByName.get(norm(r.adm1_name));
    if (!iso) throw new Error(`no ISO 3166-2 match for state ${r.adm1_name}`);
    return { code: r.adm1_pcode, name: r.adm1_name, isoCode: iso, type: fct ? "federal_capital_territory" : "state" };
  })
  .sort((a, b) => a.code.localeCompare(b.code));
const fctCode = states.find((s) => s.type === "federal_capital_territory")?.code;
if (!fctCode) throw new Error(`FCT not found (${FCT_PCODE_NAME})`);

const lgas = rows("nga_admin2")
  .map((r) => ({
    code: r.adm2_pcode,
    name: r.adm2_name,
    stateCode: r.adm1_pcode,
    type: r.adm1_pcode === fctCode ? "area_council" : "lga",
  }))
  .sort((a, b) => a.code.localeCompare(b.code));

const data = {
  meta: {
    country: "NG",
    dataset: "Nigeria - Subnational Administrative Boundaries (OCHA COD-AB, nga_admin_boundaries.xlsx)",
    originalSource: "Office of the Surveyor General of the Federation of Nigeria (OSGOF), eHealth Africa, UN Cartographic Section",
    url: "https://data.humdata.org/dataset/cod-ab-nga",
    sourceLastModified: "2026-04-16",
    boundaryValidOn: "2019-04-17",
    retrieved: "2026-10-28",
    license: "CC BY-IGO 3.0 (credit: OSGOF / eHealth Africa / UNCS via OCHA HDX)",
    note: "Level names: 36 states + FCT; 768 LGAs in the states + 6 FCT Area Councils. Sheet rows are copied verbatim.",
  },
  states,
  lgas,
};
writeFileSync("data/geo/ng-admin-units.json", JSON.stringify(data, null, 1) + "\n");

const q = (s) => `'${s.replace(/'/g, "''")}'`;
const sql = [
  "-- GENERATED by scripts/build-ng-admin-units.mjs from data/geo/ng-admin-units.json -- do not edit by hand.",
  "-- Idempotent: upserts on (country_code, code); never deletes. Source: OCHA COD-AB Nigeria (CC BY-IGO).",
  "insert into public.geo_admin_units (country_code, code, name, unit_type, level, parent_code, iso_code, source) values",
  [
    ...states.map((s) => `  ('NG', ${q(s.code)}, ${q(s.name)}, ${q(s.type)}, 1, null, ${q(s.isoCode)}, 'ocha-cod-ab-nga')`),
    ...lgas.map((l) => `  ('NG', ${q(l.code)}, ${q(l.name)}, ${q(l.type)}, 2, ${q(l.stateCode)}, null, 'ocha-cod-ab-nga')`),
  ].join(",\n"),
  "on conflict (country_code, code) do update set",
  "  name = excluded.name, unit_type = excluded.unit_type, level = excluded.level,",
  "  parent_code = excluded.parent_code, iso_code = excluded.iso_code, source = excluded.source;",
  "",
].join("\n");
writeFileSync("supabase/seed/ng_admin_units.sql", sql);
console.log(`states=${states.length} lgas=${lgas.length}`);
