// Writes components/wordCreator/word-sizes.css: for every font size the editor can show (half points from 6pt to 100pt, and the
// sizes headings and the title use), the font size to ask the browser for and the letter-spacing correction. See sizeFix in model.ts.
//   node --no-warnings --import ./tests/scanner/register.mjs tests/wordCreator/gen-sizes.mjs
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { sizeFix } from "../../utils/wordCreator/model.ts";

const root = path.join(path.dirname(fileURLToPath(import.meta.url)), "..", "..");
const num = (n) => String(n).replace(/(\.\d*?)0+$/, "$1").replace(/\.$/, "");
const rules = [];
for (let half = 12; half <= 200; half++) {
  const pt = half / 2;
  const fix = sizeFix(pt);
  if (!fix) continue;
  rules.push(`.wc-page [style*="font-size: ${num(pt)}pt"] {\n  font-size: ${num(fix.askPx)}px !important;\n  letter-spacing: ${num(fix.letterSpacingPx)}px !important;\n}`);
}
const base = (selector, pt) => {
  const fix = sizeFix(pt);
  return fix ? `${selector} {\n  font-size: ${num(fix.askPx)}px;\n  letter-spacing: ${num(fix.letterSpacingPx)}px;\n}` : "";
};
const css = `/* GENERATED by tests/wordCreator/gen-sizes.mjs from sizeFix() in utils/wordCreator/model.ts. Do not edit by hand.
   Chrome lays text out at a font size cut to two decimals of a pixel, which makes lines 0.03-0.04% narrower than in Word and lets a line
   take a word that Word would wrap. Each size is asked for at the nearest hundredth of a pixel instead, with the rest taken out of the
   letter spacing. Sizes that are whole pixels need nothing. */
${[
  base(".wc-page.ProseMirror", 11),
  base(".wc-page h1", 20),
  base(".wc-page h2", 16),
  base(".wc-page h3", 13),
  base('.wc-page p[data-variant="title"]', 26),
  base('.wc-page p[data-variant="subtitle"]', 14),
]
  .filter(Boolean)
  .join("\n")}
${rules.join("\n")}
`;
fs.writeFileSync(path.join(root, "components", "wordCreator", "word-sizes.css"), css);
console.log("wrote", rules.length, "size rules");
