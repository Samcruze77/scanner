// Writes components/wordCreator/word-fonts.css: the editor's Calibri, Arial and Times New Roman, so that text wraps the same on every
// device. A device that has the real font uses it (local()); every other one gets the open, metric-compatible twin that the Word -> PDF
// converter already ships (Carlito, Arimo, Tinos: SIL Open Font License 1.1, copied into public/fonts/docx by scripts/copy-font-assets.mjs).
// The twins have the same letter widths and line heights as the originals, so a line breaks in the same place in either. The unicode
// ranges come from the @fontsource packages' own stylesheets.
//   node tests/wordCreator/gen-fonts.mjs
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.join(path.dirname(fileURLToPath(import.meta.url)), "..", "..");
const SUBSETS = ["latin", "latin-ext", "cyrillic", "greek"];
const FAMILIES = [
  { twin: "carlito", family: "Calibri", locals: { "400-normal": ["Calibri", "Calibri-Regular"], "700-normal": ["Calibri Bold", "Calibri-Bold"], "400-italic": ["Calibri Italic", "Calibri-Italic"], "700-italic": ["Calibri Bold Italic", "Calibri-BoldItalic"] } },
  { twin: "arimo", family: "Arial", locals: { "400-normal": ["Arial", "ArialMT"], "700-normal": ["Arial Bold", "Arial-BoldMT"], "400-italic": ["Arial Italic", "Arial-ItalicMT"], "700-italic": ["Arial Bold Italic", "Arial-BoldItalicMT"] } },
  { twin: "tinos", family: "Times New Roman", locals: { "400-normal": ["Times New Roman", "TimesNewRomanPSMT"], "700-normal": ["Times New Roman Bold", "TimesNewRomanPS-BoldMT"], "400-italic": ["Times New Roman Italic", "TimesNewRomanPS-ItalicMT"], "700-italic": ["Times New Roman Bold Italic", "TimesNewRomanPS-BoldItalicMT"] } },
];
const faces = [];
for (const f of FAMILIES) {
  for (const style of ["normal", "italic"]) {
    for (const weight of ["400", "700"]) {
      const sheet = fs.readFileSync(path.join(root, "node_modules", "@fontsource", f.twin, `${weight}${style === "italic" ? "-italic" : ""}.css`), "utf8");
      for (const m of sheet.matchAll(/\/\* (\S+) \*\/\s*@font-face \{[^}]*?unicode-range: ([^;]+);/g)) {
        const name = m[1]; // carlito-latin-ext-400-normal
        const subset = SUBSETS.find((s) => name === `${f.twin}-${s}-${weight}-${style}`);
        if (!subset) continue;
        const locals = f.locals[`${weight}-${style}`].map((n) => `local("${n}")`).join(", ");
        faces.push(`@font-face {\n  font-family: "${f.family}";\n  font-style: ${style};\n  font-weight: ${weight};\n  font-display: swap;\n  src: ${locals}, url(/fonts/docx/${name}.woff) format("woff");\n  unicode-range: ${m[2]};\n}`);
      }
    }
  }
}
const css = `/* GENERATED by tests/wordCreator/gen-fonts.mjs. Do not edit by hand. */
${faces.join("\n")}
`;
fs.writeFileSync(path.join(root, "components", "wordCreator", "word-fonts.css"), css);
console.log("wrote", faces.length, "font faces");
